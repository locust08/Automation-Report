create or replace function public.m03_ads_validate_mock_change_request_v2(
  p_request_id uuid, p_actor_id uuid, p_trusted_ip inet, p_trusted_user_agent text, p_idempotency_key text
) returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_request public.m03_ads_change_requests; v_claim public.m03_ads_idempotency_claims; v_revision public.m03_ads_change_request_revisions; v_actor record; v_payload jsonb; v_issues jsonb; v_hash text; v_next integer; v_from text; v_response jsonb;
begin
  select * into v_actor from m03_ads_internal.resolve_operator(p_actor_id,p_trusted_ip);
  select * into v_claim from public.m03_ads_idempotency_claims where action='validate_v2' and idempotency_key=p_idempotency_key;
  if found then return v_claim.response_snapshot; end if;
  select * into v_request from public.m03_ads_change_requests where id=p_request_id for update;
  if not found then raise exception 'change_request_not_found'; end if;
  if v_request.status not in ('draft','validation_failed') then raise exception 'request_not_editable_for_validation'; end if;
  v_from:=v_request.status;
  update public.m03_ads_change_requests set status='validation_in_progress',updated_at=clock_timestamp() where id=p_request_id;
  insert into public.m03_ads_change_events(request_id,event_type,from_status,to_status,actor_id,actor_name,trusted_ip,trusted_user_agent)
  values(p_request_id,'validation_started',v_from,'validation_in_progress',p_actor_id,v_actor.actor_name,p_trusted_ip,left(p_trusted_user_agent,1000));
  select coalesce(pg_catalog.jsonb_agg(pg_catalog.jsonb_build_object('entity_type',entity_type,'entity_identity',entity_identity,'field_path',field_path,'value_type',value_type,'baseline_value',baseline_value,'proposed_value',proposed_value,'evidence',evidence,'platform_resource_mapping',platform_resource_mapping) order by entity_type,entity_identity,field_path),'[]'::jsonb) into v_payload from public.m03_ads_change_items where request_id=p_request_id;
  v_issues:=case when pg_catalog.jsonb_array_length(v_payload)=0 then pg_catalog.jsonb_build_array(pg_catalog.jsonb_build_object('path','items','message','At least one proposed change is required.','severity','error')) else '[]'::jsonb end;
  v_payload:=pg_catalog.jsonb_build_object('platform',v_request.platform,'workflow_mode','mock','account_identity',v_request.account_identity,'campaign_identity',v_request.campaign_identity,'source_m04_plan_id',v_request.source_m04_plan_id,'source_m04_revision_id',v_request.source_m04_revision_id,'source_m05_recommendation_ref',v_request.source_m05_recommendation_ref,'items',v_payload);
  v_hash:=pg_catalog.encode(extensions.digest(pg_catalog.convert_to(v_payload::text,'utf8'),'sha256'),'hex');
  select coalesce(max(revision_number),0)+1 into v_next from public.m03_ads_change_request_revisions where request_id=p_request_id;
  insert into public.m03_ads_change_request_revisions(request_id,revision_number,canonical_payload,payload_hash,evidence,validation_issues,created_by_id)
  values(p_request_id,v_next,v_payload,v_hash,pg_catalog.jsonb_build_object('trusted_ip',p_trusted_ip,'source_m05_recommendation_ref',v_request.source_m05_recommendation_ref),v_issues,p_actor_id) returning * into v_revision;
  insert into public.m03_ads_validation_records(request_id,revision_id,result,issues,snapshot,validated_by_id) values(p_request_id,v_revision.id,case when pg_catalog.jsonb_array_length(v_issues)=0 then 'passed' else 'failed' end,v_issues,pg_catalog.jsonb_build_object('payload_hash',v_hash,'workflow_mode','mock','provider_execution_locked',true),p_actor_id);
  update public.m03_ads_change_requests set status=case when pg_catalog.jsonb_array_length(v_issues)=0 then 'awaiting_approval' else 'validation_failed' end,updated_at=clock_timestamp(),lock_version=lock_version+1 where id=p_request_id returning * into v_request;
  insert into public.m03_ads_change_events(request_id,revision_id,event_type,from_status,to_status,actor_id,actor_name,trusted_ip,trusted_user_agent,metadata) values(p_request_id,v_revision.id,'request_validated','validation_in_progress',v_request.status,p_actor_id,v_actor.actor_name,p_trusted_ip,left(p_trusted_user_agent,1000),pg_catalog.jsonb_build_object('payload_hash',v_hash,'issues',v_issues));
  v_response:=pg_catalog.jsonb_build_object('request_id',p_request_id,'revision_id',v_revision.id,'payload_hash',v_hash,'status',v_request.status,'issues',v_issues,'lock_version',v_request.lock_version);
  insert into public.m03_ads_idempotency_claims(action,request_id,idempotency_key,response_snapshot) values('validate_v2',p_request_id,p_idempotency_key,v_response);
  return v_response;
end;
$$;

