create or replace function public.m03_ads_create_mock_change_request_v2(
  p_platform text, p_title text, p_reason text, p_client_id uuid, p_account_identity text,
  p_campaign_identity text, p_source_m04_plan_id bigint, p_source_m04_revision_id bigint,
