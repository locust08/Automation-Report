begin
  select * into v_actor from m03_ads_internal.resolve_operator(p_actor_id, p_trusted_ip);
  if p_platform not in ('google','meta','tiktok') then raise exception 'unsupported_platform'; end if;
  if pg_catalog.jsonb_typeof(p_items) <> 'array' or pg_catalog.jsonb_array_length(p_items) = 0 then raise exception 'at_least_one_change_item_required'; end if;
  select * into v_claim from public.m03_ads_idempotency_claims where action='create_v2' and idempotency_key=p_idempotency_key;
  if found then return v_claim.response_snapshot; end if;
  insert into public.m03_ads_change_requests(platform,title,reason,client_id,account_identity,campaign_identity,source_m04_plan_id,source_m04_revision_id,source_m05_recommendation_ref,rollback_of_request_id,supersedes_request_id,created_by_id,created_by_name)
