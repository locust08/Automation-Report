  end loop;
  insert into public.m03_ads_change_events(request_id,event_type,to_status,actor_id,actor_name,trusted_ip,trusted_user_agent,metadata)
  values(v_request.id,'request_created','draft',p_actor_id,v_actor.actor_name,p_trusted_ip,left(p_trusted_user_agent,1000),pg_catalog.jsonb_build_object('workflow_mode','mock','source_m05_recommendation_ref',v_request.source_m05_recommendation_ref));
  v_response := pg_catalog.jsonb_build_object('request_id',v_request.id,'status',v_request.status,'workflow_mode','mock','lock_version',v_request.lock_version);
  insert into public.m03_ads_idempotency_claims(action,request_id,idempotency_key,response_snapshot) values('create_v2',v_request.id,p_idempotency_key,v_response);
  return v_response;
end;
$$;

