-- M03-only provider-ready persistence. Provider execution remains deployment-locked.
-- Additive only: no M04, M05, reporting, authentication, credential, or legacy Google object is changed.

create table public.m03_ads_request_source_verifications (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null unique references public.m03_ads_change_requests(id) on delete cascade,
  source_kind text not null check (source_kind in ('m04_verified_launch','legacy_provider_adoption')),
  source_m04_plan_id bigint,
  source_m04_revision_id bigint,
  platform text not null check (platform in ('google','meta','tiktok')),
  provider_account_identity text not null check (btrim(provider_account_identity) <> ''),
  provider_campaign_identity text not null check (btrim(provider_campaign_identity) <> ''),
  source_revision_hash text check (source_revision_hash is null or source_revision_hash ~ '^[a-f0-9]{64}$'),
  evidence jsonb not null default '{}'::jsonb check (jsonb_typeof(evidence) = 'object'),
  verified_by_id uuid not null,
  trusted_ip inet,
  trusted_user_agent text,
  idempotency_key text not null unique,
  verified_at timestamptz not null default clock_timestamp(),
  created_at timestamptz not null default clock_timestamp(),
  constraint m03_source_kind_shape check (
    (source_kind = 'm04_verified_launch' and source_m04_plan_id is not null and source_m04_revision_id is not null and source_revision_hash is not null)
    or
    (source_kind = 'legacy_provider_adoption' and source_m04_plan_id is null and source_m04_revision_id is null)
  )
);

create table public.m03_ads_provider_baseline_snapshots (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null references public.m03_ads_change_requests(id) on delete cascade,
  revision_id uuid references public.m03_ads_change_request_revisions(id),
  platform text not null check (platform in ('google','meta','tiktok')),
  account_identity text not null,
  campaign_identity text not null,
  source text not null check (source in ('provider','legacy_google_compat','stored_snapshot')),
  canonical_payload jsonb not null check (jsonb_typeof(canonical_payload) = 'object'),
  payload_hash text not null check (payload_hash ~ '^[a-f0-9]{64}$'),
  captured_at timestamptz not null,
  freshness_expires_at timestamptz not null,
  captured_by_id uuid not null,
  trusted_ip inet,
  trusted_user_agent text,
  idempotency_key text not null,
  created_at timestamptz not null default clock_timestamp(),
  unique (request_id, idempotency_key)
);

create table public.m03_ads_provider_resource_mappings (
  id bigint generated by default as identity primary key,
  request_id uuid not null references public.m03_ads_change_requests(id) on delete cascade,
  item_id uuid not null unique references public.m03_ads_change_items(id) on delete cascade,
  platform text not null check (platform in ('google','meta','tiktok')),
  provider_resource_type text not null,
  previous_resource_identity text,
  replacement_resource_identity text,
  replacement_stage text not null default 'not_required' check (replacement_stage in (
    'not_required','replacement_planned','replacement_created_inactive','replacement_verified',
    'replacement_activated','previous_resource_disabled','completed','compensation_required'
  )),
  capability_registry_version integer not null check (capability_registry_version > 0),
  operation_plan jsonb not null default '[]'::jsonb check (jsonb_typeof(operation_plan) = 'array'),
  rollback_evidence jsonb not null default '{}'::jsonb check (jsonb_typeof(rollback_evidence) = 'object'),
  created_at timestamptz not null default clock_timestamp(),
  updated_at timestamptz not null default clock_timestamp()
);

