  add column if not exists provider_request jsonb not null default '{}'::jsonb check (jsonb_typeof(provider_request) = 'object'),
  add column if not exists normalized_error jsonb not null default '{}'::jsonb check (jsonb_typeof(normalized_error) = 'object'),
  add column if not exists updated_at timestamptz not null default clock_timestamp();

create index m03_ads_source_verifications_request_idx on public.m03_ads_request_source_verifications (request_id, verified_at desc);
