  on public.m04_ads_campaign_readiness_checks (revision_id, created_at desc);

create or replace function public.m04_ads_is_trusted_network(p_ip inet)
returns boolean language sql stable security invoker set search_path = public, pg_temp
as $$
  select coalesce(bool_or(p_ip <<= network), false)
  from public.m04_ads_trusted_networks
  where is_active;
$$;

create or replace function public.m04_ads_record_campaign_readiness(
  p_plan_id bigint,
  p_revision_id bigint,
  p_expected_revision_hash text,
  p_result text,
  p_checks jsonb,
  p_issues jsonb,
  p_validation_snapshot jsonb,
  p_actor_id uuid,
  p_trusted_ip inet,
  p_trusted_user_agent text,
  p_request_idempotency_key text
) returns public.m04_ads_campaign_readiness_checks
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_plan public.m04_ads_campaign_plans;
  v_revision public.m04_ads_campaign_plan_revisions;
  v_row public.m04_ads_campaign_readiness_checks;
begin
  if p_result not in ('passed', 'failed', 'attention') then
    raise exception 'invalid_readiness_result';
  end if;

  select * into v_plan from public.m04_ads_campaign_plans where id = p_plan_id for share;
  if not found then raise exception 'campaign_not_found'; end if;
  if v_plan.active_revision_id is distinct from p_revision_id then raise exception 'stale_campaign_revision'; end if;

  select * into v_revision from public.m04_ads_campaign_plan_revisions where id = p_revision_id and plan_id = p_plan_id;
  if not found or v_revision.payload_hash is distinct from p_expected_revision_hash then
    raise exception 'revision_hash_mismatch';
  end if;

  select * into v_row from public.m04_ads_campaign_readiness_checks
    where plan_id = p_plan_id and request_idempotency_key = p_request_idempotency_key;
  if found then return v_row; end if;

  insert into public.m04_ads_campaign_readiness_checks (
    plan_id, revision_id, revision_hash, result, checks, issues, validation_snapshot,
    actor_id, trusted_ip, trusted_user_agent, request_idempotency_key
  ) values (
    p_plan_id, p_revision_id, p_expected_revision_hash, p_result,
    coalesce(p_checks, '[]'::jsonb), coalesce(p_issues, '[]'::jsonb), coalesce(p_validation_snapshot, '{}'::jsonb),
    p_actor_id, p_trusted_ip, left(p_trusted_user_agent, 1000), p_request_idempotency_key
  ) returning * into v_row;

  insert into public.m04_ads_campaign_audit_events (
    plan_id, revision_id, event_type, actor_id, trusted_ip, trusted_user_agent, metadata
  ) values (
    p_plan_id, p_revision_id, 'readiness_checked', p_actor_id, p_trusted_ip,
    left(p_trusted_user_agent, 1000), jsonb_build_object('readiness_check_id', v_row.id, 'result', v_row.result)
  );
  return v_row;
end;
$$;

create table public.m03_ads_change_requests (
  id uuid primary key default gen_random_uuid(),
  platform text not null check (platform in ('google', 'meta', 'tiktok')),
  workflow_mode text not null default 'mock' check (workflow_mode = 'mock'),
  status text not null default 'draft' check (status in ('draft', 'validation_failed', 'awaiting_approval', 'approved', 'cancelled', 'provider_execution_locked')),
  title text not null,
  reason text not null,
  client_id uuid,
  account_identity text not null,
  campaign_identity text not null,
  source_m04_plan_id bigint references public.m04_ads_campaign_plans(id),
  source_m04_revision_id bigint references public.m04_ads_campaign_plan_revisions(id),
  created_by_id uuid not null,
  created_by_name text not null,
  created_at timestamptz not null default clock_timestamp(),
  updated_at timestamptz not null default clock_timestamp(),
