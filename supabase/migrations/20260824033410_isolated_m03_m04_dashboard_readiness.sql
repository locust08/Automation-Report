create or replace function public.m03_ads_create_mock_change_request(
  p_platform text,
  p_title text,
  p_reason text,
  p_client_id uuid,
  p_account_identity text,
  p_campaign_identity text,
  p_source_m04_plan_id bigint,
  p_source_m04_revision_id bigint,
  p_items jsonb,
  p_actor_id uuid,
  p_actor_name text,
  p_idempotency_key text
) returns jsonb
language plpgsql security invoker set search_path = public, extensions, pg_temp
as $$
declare v_request public.m03_ads_change_requests; v_claim public.m03_ads_idempotency_claims; v_item jsonb;
begin
  if p_platform not in ('google','meta','tiktok') then raise exception 'unsupported_platform'; end if;
  select * into v_claim from public.m03_ads_idempotency_claims where action='create' and idempotency_key=p_idempotency_key;
  if found then return v_claim.response_snapshot; end if;
  insert into public.m03_ads_change_requests(platform,title,reason,client_id,account_identity,campaign_identity,source_m04_plan_id,source_m04_revision_id,created_by_id,created_by_name)
  values(p_platform,trim(p_title),trim(p_reason),p_client_id,trim(p_account_identity),trim(p_campaign_identity),p_source_m04_plan_id,p_source_m04_revision_id,p_actor_id,trim(p_actor_name)) returning * into v_request;
  for v_item in select value from jsonb_array_elements(coalesce(p_items,'[]'::jsonb)) loop
    insert into public.m03_ads_change_items(request_id,entity_type,entity_identity,field_path,baseline_value,proposed_value,evidence)
    values(v_request.id,v_item->>'entity_type',v_item->>'entity_identity',v_item->>'field_path',v_item->'baseline_value',v_item->'proposed_value',coalesce(v_item->'evidence','{}'::jsonb));
  end loop;
  insert into public.m03_ads_change_events(request_id,event_type,to_status,actor_id,actor_name,metadata)
    values(v_request.id,'request_created','draft',p_actor_id,p_actor_name,jsonb_build_object('workflow_mode','mock'));
  insert into public.m03_ads_idempotency_claims(action,request_id,idempotency_key,response_snapshot)
    values('create',v_request.id,p_idempotency_key,jsonb_build_object('request_id',v_request.id,'status',v_request.status,'workflow_mode','mock')) returning * into v_claim;
  return v_claim.response_snapshot;
end; $$;

create or replace function public.m03_ads_validate_mock_change_request(
  p_request_id uuid,
  p_actor_id uuid,
  p_actor_name text,
  p_idempotency_key text
) returns jsonb
language plpgsql security invoker set search_path = public, extensions, pg_temp
as $$
declare v_request public.m03_ads_change_requests; v_claim public.m03_ads_idempotency_claims; v_revision public.m03_ads_change_request_revisions; v_payload jsonb; v_issues jsonb; v_hash text; v_next integer;
begin
  select * into v_claim from public.m03_ads_idempotency_claims where action='validate' and idempotency_key=p_idempotency_key;
  if found then return v_claim.response_snapshot; end if;
  select * into v_request from public.m03_ads_change_requests where id=p_request_id for update;
  if not found then raise exception 'change_request_not_found'; end if;
  select coalesce(jsonb_agg(jsonb_build_object('entity_type',entity_type,'entity_identity',entity_identity,'field_path',field_path,'baseline_value',baseline_value,'proposed_value',proposed_value,'evidence',evidence) order by entity_type,entity_identity,field_path),'[]'::jsonb)
    into v_payload from public.m03_ads_change_items where request_id=p_request_id;
  v_issues := case when jsonb_array_length(v_payload)=0 then jsonb_build_array(jsonb_build_object('path','items','message','At least one proposed change is required.')) else '[]'::jsonb end;
  v_hash := encode(extensions.digest(convert_to(v_payload::text,'utf8'),'sha256'),'hex');
  select coalesce(max(revision_number),0)+1 into v_next from public.m03_ads_change_request_revisions where request_id=p_request_id;
  insert into public.m03_ads_change_request_revisions(request_id,revision_number,canonical_payload,payload_hash,evidence,validation_issues,created_by_id)
    values(p_request_id,v_next,jsonb_build_object('platform',v_request.platform,'workflow_mode','mock','items',v_payload),v_hash,jsonb_build_object('source_m04_plan_id',v_request.source_m04_plan_id,'source_m04_revision_id',v_request.source_m04_revision_id),v_issues,p_actor_id) returning * into v_revision;
  insert into public.m03_ads_validation_records(request_id,revision_id,result,issues,snapshot,validated_by_id)
    values(p_request_id,v_revision.id,case when jsonb_array_length(v_issues)=0 then 'passed' else 'failed' end,v_issues,jsonb_build_object('payload_hash',v_hash,'workflow_mode','mock'),p_actor_id);
  update public.m03_ads_change_requests set status=case when jsonb_array_length(v_issues)=0 then 'awaiting_approval' else 'validation_failed' end,updated_at=clock_timestamp(),lock_version=lock_version+1 where id=p_request_id returning * into v_request;
  insert into public.m03_ads_change_events(request_id,revision_id,event_type,from_status,to_status,actor_id,actor_name,metadata)
    values(p_request_id,v_revision.id,'request_validated','draft',v_request.status,p_actor_id,p_actor_name,jsonb_build_object('payload_hash',v_hash,'issues',v_issues));
  insert into public.m03_ads_idempotency_claims(action,request_id,idempotency_key,response_snapshot)
    values('validate',p_request_id,p_idempotency_key,jsonb_build_object('request_id',p_request_id,'revision_id',v_revision.id,'payload_hash',v_hash,'status',v_request.status,'issues',v_issues)) returning * into v_claim;
  return v_claim.response_snapshot;
end; $$;

create or replace function public.m03_ads_approve_mock_change_request(
  p_request_id uuid,
  p_actor_id uuid,
  p_actor_name text,
  p_comment text,
  p_idempotency_key text
) returns jsonb
language plpgsql security invoker set search_path = public, pg_temp
as $$
declare v_request public.m03_ads_change_requests; v_revision public.m03_ads_change_request_revisions; v_claim public.m03_ads_idempotency_claims; v_approval public.m03_ads_change_approvals;
begin
  select * into v_claim from public.m03_ads_idempotency_claims where action='approve' and idempotency_key=p_idempotency_key;
  if found then return v_claim.response_snapshot; end if;
  select * into v_request from public.m03_ads_change_requests where id=p_request_id for update;
  if not found then raise exception 'change_request_not_found'; end if;
  if v_request.workflow_mode <> 'mock' then raise exception 'provider_execution_locked'; end if;
  if v_request.status <> 'awaiting_approval' then raise exception 'request_not_ready_for_approval'; end if;
  select * into v_revision from public.m03_ads_change_request_revisions where request_id=p_request_id order by revision_number desc limit 1;
  insert into public.m03_ads_change_approvals(request_id,revision_id,revision_hash,comment,approved_by_id,request_idempotency_key)
    values(p_request_id,v_revision.id,v_revision.payload_hash,p_comment,p_actor_id,p_idempotency_key) returning * into v_approval;
  update public.m03_ads_change_requests set status='approved',updated_at=clock_timestamp(),lock_version=lock_version+1 where id=p_request_id;
  insert into public.m03_ads_change_events(request_id,revision_id,event_type,from_status,to_status,actor_id,actor_name,metadata)
    values(p_request_id,v_revision.id,'request_approved','awaiting_approval','approved',p_actor_id,p_actor_name,jsonb_build_object('approval_id',v_approval.id,'provider_execution_locked',true));
  insert into public.m03_ads_idempotency_claims(action,request_id,idempotency_key,response_snapshot)
    values('approve',p_request_id,p_idempotency_key,jsonb_build_object('request_id',p_request_id,'approval_id',v_approval.id,'status','approved','provider_execution_locked',true)) returning * into v_claim;
  return v_claim.response_snapshot;
end; $$;

